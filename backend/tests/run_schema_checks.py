"""Run integration checks in a new disposable Docker database with verified TLS."""

import argparse
import asyncio
import ipaddress
import json
import os
import subprocess
import sys
import tempfile
import time
import uuid
from datetime import UTC, datetime, timedelta
from pathlib import Path

import aiomysql
from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import rsa
from cryptography.x509.oid import NameOID

BACKEND = Path(__file__).resolve().parents[1]


def create_test_certificates(path: Path) -> None:
    now = datetime.now(UTC)
    key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    name = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, "Isolated schema test CA")])
    ca = (
        x509.CertificateBuilder()
        .subject_name(name)
        .issuer_name(name)
        .public_key(key.public_key())
        .serial_number(x509.random_serial_number())
        .not_valid_before(now - timedelta(minutes=1))
        .not_valid_after(now + timedelta(days=1))
        .add_extension(x509.BasicConstraints(ca=True, path_length=0), critical=True)
        .sign(key, hashes.SHA256())
    )
    server_key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    server = (
        x509.CertificateBuilder()
        .subject_name(x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, "localhost")]))
        .issuer_name(name)
        .public_key(server_key.public_key())
        .serial_number(x509.random_serial_number())
        .not_valid_before(now - timedelta(minutes=1))
        .not_valid_after(now + timedelta(days=1))
        .add_extension(
            x509.SubjectAlternativeName(
                [
                    x509.DNSName("localhost"),
                    x509.IPAddress(ipaddress.ip_address("127.0.0.1")),
                ]
            ),
            critical=False,
        )
        .sign(key, hashes.SHA256())
    )
    (path / "ca.pem").write_bytes(ca.public_bytes(serialization.Encoding.PEM))
    (path / "server.pem").write_bytes(server.public_bytes(serialization.Encoding.PEM))
    (path / "server-key.pem").write_bytes(
        server_key.private_bytes(
            serialization.Encoding.PEM,
            serialization.PrivateFormat.TraditionalOpenSSL,
            serialization.NoEncryption(),
        )
    )
    (path / "tidb.toml").write_text(
        '[security]\nssl-ca="/tls/ca.pem"\nssl-cert="/tls/server.pem"\n'
        'ssl-key="/tls/server-key.pem"\nrequire-secure-transport=true\n'
    )
    # Disposable test key only. MySQL's container UID must be able to read the bind mount.
    # No production secrets or CA signing private key are written to disk.
    path.chmod(0o755)
    for file in path.iterdir():
        file.chmod(0o644)


async def create_database(port: int, ca_file: Path, database: str) -> None:
    import ssl

    deadline = time.monotonic() + 60
    while True:
        try:
            connection = await aiomysql.connect(
                host="127.0.0.1",
                port=port,
                user="root",
                connect_timeout=3,
                ssl=ssl.create_default_context(cafile=str(ca_file)),
            )
            break
        except (OSError, aiomysql.OperationalError):
            if time.monotonic() >= deadline:
                raise RuntimeError("The isolated TLS database did not become ready") from None
            await asyncio.sleep(1)
    try:
        async with connection.cursor() as cursor:
            # Database name is generated by this runner, never supplied by a user.
            await cursor.execute(
                f"CREATE DATABASE `{database}` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci"
            )
    finally:
        connection.close()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--engine", choices=["mysql", "tidb"], required=True)
    parser.add_argument(
        "--suite",
        choices=[
            "schema",
            "auth",
            "booking",
            "folder",
            "realtime",
            "frontend",
            "tasks",
            "admin",
            "safeguards",
            "collaboration",
            "operations",
            "invoices",
            "security",
            "coverage",
            "backup",
            "observability",
            "load",
            "integrity-performance",
            "search-performance",
        ],
        default="schema",
    )
    parser.add_argument("--report", type=Path, required=True)
    args = parser.parse_args()
    docker_env = os.environ.copy()
    for key in (
        "DOCKER_HOST",
        "DOCKER_CONTEXT",
        "DOCKER_TLS",
        "DOCKER_TLS_VERIFY",
        "DOCKER_CERT_PATH",
    ):
        docker_env.pop(key, None)

    def docker(*arguments: str) -> str:
        return subprocess.check_output(
            ["docker", "--host=unix:///var/run/docker.sock", *arguments],
            env=docker_env,
            text=True,
            timeout=180,
        ).strip()

    docker("info", "--format", "{{.ServerVersion}}")
    identifier = uuid.uuid4().hex[:12]
    name = f"booking-schema-{args.engine}-{identifier}"
    database = f"booking_schema_{identifier}_test"
    with tempfile.TemporaryDirectory(prefix="booking-schema-tls-") as directory:
        certificate_path = Path(directory)
        create_test_certificates(certificate_path)
        internal_port = "3306" if args.engine == "mysql" else "4000"
        options = [
            "run",
            "--rm",
            "-d",
            "--name",
            name,
            "-p",
            f"127.0.0.1::{internal_port}",
            "--mount",
            f"type=bind,src={directory},dst=/tls,readonly",
        ]
        if args.engine == "mysql":
            # No externally accessible listener or reusable production credential exists.
            options += [
                "-e",
                "MYSQL_ALLOW_EMPTY_PASSWORD=yes",
                "-e",
                "MYSQL_ROOT_HOST=%",
                "mysql:8.0",
                "--ssl-ca=/tls/ca.pem",
                "--ssl-cert=/tls/server.pem",
                "--ssl-key=/tls/server-key.pem",
                "--require-secure-transport=ON",
                "--character-set-server=utf8mb4",
                "--collation-server=utf8mb4_unicode_ci",
            ]
        else:
            options += [
                "pingcap/tidb:v8.5.0",
                "--store=unistore",
                "--path=/tmp/tidb",
                "--config=/tls/tidb.toml",
            ]
        try:
            docker(*options)
            ports = json.loads(
                docker("inspect", "--format", "{{json .NetworkSettings.Ports}}", name)
            )
            port = int(ports[f"{internal_port}/tcp"][0]["HostPort"])
            asyncio.run(create_database(port, certificate_path / "ca.pem", database))
            test_env = os.environ.copy()
            url = f"mysql+aiomysql://root@127.0.0.1:{port}/{database}?charset=utf8mb4"
            test_env.update(
                {
                    "APP_ENV": "test",
                    "DATABASE_URL": url,
                    "DATABASE_SSL": "true",
                    "DB_SSL": "true",
                    "DATABASE_SSL_CA": str(certificate_path / "ca.pem"),
                    "SCHEMA_TEST_DATABASE_URL": url,
                    "SCHEMA_TEST_SSL_CA": str(certificate_path / "ca.pem"),
                    "SCHEMA_TEST_REPORT": str(args.report.resolve()),
                }
            )
            args.report.resolve().parent.mkdir(parents=True, exist_ok=True)
            test_file = {
                "schema": "tests/test_schema_database.py",
                "auth": "tests/test_auth_database.py",
                "booking": "tests/test_booking_database.py",
                "folder": "tests/test_folder_database.py",
                "realtime": "tests/test_realtime_database.py",
                "frontend": "tests/test_frontend_database.py",
                "tasks": "tests/test_tasks_database.py",
                "admin": "tests/test_admin_database.py",
                "safeguards": "tests/test_safeguards_database.py",
                "collaboration": "tests/test_collaboration_database.py",
                "operations": "tests/test_operations_database.py",
                "invoices": "tests/test_invoices_database.py",
                "security": "tests/test_hardening_database.py",
                "coverage": "tests",
                "backup": "tests/test_backup_database.py",
                "observability": "tests/test_observability_database.py",
                "load": "tests/test_load_database.py",
                "integrity-performance": "tests/test_integrity_performance.py",
                "search-performance": "tests/test_search_performance.py",
            }[args.suite]
            test_command = [sys.executable, "-m", "pytest", test_file]
            if args.suite == "booking":
                test_command.append("tests/test_booking_creation_database.py")
            test_command.extend(["-q", "-x"])
            if args.suite not in {"schema", "search-performance", "integrity-performance", "load"}:
                test_command.append(f"--junitxml={args.report.resolve()}")
            if args.suite == "coverage":
                for test_stem in [
                    "frontend_database",
                    "schema_database",
                    "integrity_performance",
                    "search_performance",
                    "load_database",
                ]:
                    test_command.append(f"--ignore=tests/test_{test_stem}.py")
                test_command.extend(
                    [
                        "--cov=app.services",
                        "--cov-report=term-missing",
                        f"--cov-report=json:{args.report.resolve().with_suffix('.coverage.json')}",
                        f"--cov-report=xml:{args.report.resolve().with_suffix('.coverage.xml')}",
                        "--cov-fail-under=80",
                    ]
                )
            if args.suite == "frontend":
                test_command.append("--tb=short")
            subprocess.run(
                test_command,
                cwd=BACKEND,
                env=test_env,
                check=True,
                timeout=900 if args.suite in {"coverage", "load"} else 360,
            )
            print(f"{args.engine} {args.suite}: checks passed; report: {args.report}")
        finally:
            # Remove only this runner's unique disposable container, even after a failed test.
            subprocess.run(
                ["docker", "--host=unix:///var/run/docker.sock", "rm", "-f", name],
                env=docker_env,
                stdout=subprocess.DEVNULL,
                check=False,
                timeout=30,
            )


if __name__ == "__main__":
    main()
