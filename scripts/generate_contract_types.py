"""Generate TypeScript wire types from Prompt 1B Pydantic serialization schemas."""

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.schemas.auth import AUTH_MODELS
from app.schemas.bookings import BOOKING_MODELS
from app.schemas.contracts import CONTRACT_ENUMS, CONTRACT_MODELS, ErrorCode

OUTPUT = ROOT / "frontend/src/types/api.generated.ts"


def ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[1]
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    if "anyOf" in schema:
        return " | ".join(dict.fromkeys(ts_type(part) for part in schema["anyOf"]))
    kind = schema.get("type")
    if kind in {"integer", "number"}:
        return "number"
    if kind == "string":
        return "string"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        return f"Array<{ts_type(schema.get('items', {}))}>"
    if kind == "object":
        if "properties" in schema:
            required = set(schema.get("required", []))
            fields = [
                f"{json.dumps(name)}{'' if name in required else '?'}: {ts_type(value)}"
                for name, value in schema["properties"].items()
            ]
            return "{ " + "; ".join(fields) + " }"
        additional = schema.get("additionalProperties", {})
        value = ts_type(additional) if isinstance(additional, dict) else "unknown"
        return "{ [key: string]: " + value + " }"
    if not schema:
        return "unknown"
    raise ValueError(f"Unsupported schema shape: {schema}")


def generate() -> str:
    definitions: dict[str, Any] = {}
    for model in (*CONTRACT_MODELS, *AUTH_MODELS, *BOOKING_MODELS):
        schema = model.model_json_schema(mode="serialization")
        for name, definition in schema.pop("$defs", {}).items():
            if name in definitions and definitions[name] != definition:
                raise ValueError(f"Conflicting schema definition: {name}")
            definitions[name] = definition
        definitions[model.__name__] = schema
    for enum in CONTRACT_ENUMS:
        definitions[enum.__name__] = {"enum": [item.value for item in enum]}
    # Pydantic emits an unconstrained schema for its built-in JsonValue type.
    # Preserve the documented JSON-only recursive type in TypeScript.
    definitions["JsonValue"] = {
        "anyOf": [
            {"type": "null"},
            {"type": "boolean"},
            {"type": "number"},
            {"type": "string"},
            {"type": "array", "items": {"$ref": "#/JsonValue"}},
            {"type": "object", "additionalProperties": {"$ref": "#/JsonValue"}},
        ]
    }
    lines = [
        "// Generated by scripts/generate_contract_types.py. Do not edit manually.",
        "// Sources: backend/app/schemas/{contracts,auth,bookings}.py. Timestamps use UTC ISO 8601 ms.",
        "",
    ]
    for name, schema in sorted(definitions.items()):
        if name in {"Page", "CursorPage"}:
            schema["properties"]["items"] = {"type": "array", "items": {"$ref": "#/T"}}
            name += "<T>"
        lines += [f"export type {name} = {ts_type(schema)}", ""]
    lines += [
        "export const ERROR_CODES = "
        + json.dumps([item.value for item in ErrorCode])
        + " as const satisfies readonly ErrorCode[]",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="Fail if committed types are out of date"
    )
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != generated:
            raise SystemExit(
                "API types are stale. Run scripts/generate_contract_types.py."
            )
        print("Generated API types match the backend contract.")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(generated)
        print(f"Generated {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
